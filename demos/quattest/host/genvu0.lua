#!/usr/bin/env lua
--[[
genvu0.lua -- VU1 routines as VU0 macro-mode C functions.

	lua demos/quattest/host/genvu0.lua demos/quattest/quat.vu > demos/quattest/quatvu0.h

Reads routines written for VU1 (a label, then lines of `upper<TAB>lower',
symbolic register names) and writes one C function per routine that
loads its inputs with lqc2, runs the same instructions as COP2 macro
instructions, and stores its outputs with sqc2.  So the text that would
go into a microprogram is what runs, not a translation by hand: the
upper mnemonic gets a v in front, acc becomes ACC, vf00 becomes $vf0,
every other name a $vfN of its own; of the lower slot only mr32 and
move are instructions here (nop and jr are not), and it runs after its
upper, which is the same thing as long as a line's two halves do not
write what the other reads.  Latencies are the hardware's problem in
macro mode: the EE stalls.

Which names are inputs and outputs comes from the ROUTINES table below,
the only thing here that knows what a routine means.
]]

local ROUTINES = {
	QuatMult      = { ins = { "A", "B" },                 outs = { "R" } },
	DQuatMult     = { ins = { "A0", "A1", "B0", "B1" },   outs = { "R0", "R1" } },
	QuatSandwich  = { ins = { "A", "U" },                 outs = { "R" } },
	DQuatSandwich = { ins = { "A", "B", "U" },            outs = { "R" } },
	QuatMatrix    = { ins = { "A", "Two" },               outs = { "MX", "MY", "MZ" } },
	DQuatMatrix   = { ins = { "A", "B", "Two" },          outs = { "MX", "MY", "MZ", "MW" } },
}

local path = arg[1] or error("usage: genvu0.lua routines.vu > out.h")
local routines, order, cur = {}, {}, nil
for line in io.lines(path) do
	line = line:gsub(";.*", ""):gsub("%s+$", "")
	local label = line:match("^(%w+):")
	if label then cur = label; routines[cur] = {}; order[#order+1] = cur
	elseif cur and line:match("%S") then
		local upper, lower = line:match("^%s*(.-)\t+(.-)$")
		if not upper then upper, lower = line:match("^%s*(.-)$"), "nop" end
		table.insert(routines[cur], { upper, lower })
	end
end

local function regnum(name, map)
	if name == "acc" then return "ACC" end
	if name == "vf00" then return "$vf0" end
	if not map[name] then map.n = map.n + 1; map[name] = "$vf" .. map.n end
	return map[name]
end

-- one instruction to macro mode: "maddaw.xyz acc,A,B" -> "vmaddaw.xyz ACC, $vf1, $vf2"
local function macro(ins, map)
	local op, args = ins:match("^([%w%.]+)%s+(.*)$")
	if not op then return nil end	-- nop
	if not op:find("%.") then op = op .. ".xyzw" end	-- the assembler wants the field spelled
	local t = {}
	for a in args:gmatch("[^,%s]+") do t[#t+1] = regnum(a, map) end
	return "v" .. op .. " " .. table.concat(t, ", ")
end

print("/* generated by demos/quattest/host/genvu0.lua from " .. path .. " -- do not edit */")
print("")
for _, name in ipairs(order) do
	local r = ROUTINES[name]
	if r then
		local map = { n = 0 }
		-- inputs and outputs first so their numbers are fixed and low
		for _, n in ipairs(r.ins) do regnum(n, map) end
		for _, n in ipairs(r.outs) do regnum(n, map) end
		local lines = {}
		for _, pair in ipairs(routines[name]) do
			local u = macro(pair[1], map)
			if u then lines[#lines+1] = u end
			local lop = pair[2]:match("^(%w+)")
			if lop == "mr32" or lop == "move" then lines[#lines+1] = macro(pair[2], map) end
		end
		local params, loads, stores, cons = {}, {}, {}, {}
		local k = 0
		for _, n in ipairs(r.ins) do
			params[#params+1] = "const float *" .. n
			loads[#loads+1] = string.format('\t\t"lqc2 %s, 0(%%%d)\\n"', map[n], k); k = k + 1
		end
		for _, n in ipairs(r.outs) do
			params[#params+1] = "float *" .. n
			stores[#stores+1] = string.format('\t\t"sqc2 %s, 0(%%%d)\\n"', map[n], k); k = k + 1
		end
		for _, n in ipairs(r.ins) do cons[#cons+1] = '"r"(' .. n .. ')' end
		for _, n in ipairs(r.outs) do cons[#cons+1] = '"r"(' .. n .. ')' end
		print(string.format("/* %s: %d instructions */", name, #lines))
		print(string.format("static void\nvu0_%s(%s)\n{\n\tasm volatile(", name, table.concat(params, ", ")))
		for _, l in ipairs(loads) do print(l) end
		for _, l in ipairs(lines) do print(string.format('\t\t"%s\\n"', l)) end
		for _, l in ipairs(stores) do print(l) end
		print("\t\t: : " .. table.concat(cons, ", ") .. ' : "memory");\n}\n')
	end
end
